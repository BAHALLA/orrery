import type { ReactNode, SVGProps } from "react";

/**
 * A small inline icon set (24×24, 1.75 stroke, currentColor).
 *
 * Inline rather than an icon package: the console needs about twenty glyphs,
 * the CSP forbids remote assets, and every dependency is one more thing the
 * supply-chain gate has to watch. Decorative by default (`aria-hidden`) — the
 * button or link around an icon carries the accessible name.
 */
type IconProps = SVGProps<SVGSVGElement> & { size?: number };

function Icon({ size = 16, children, ...props }: IconProps & { children: ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...props}
    >
      {children}
    </svg>
  );
}

